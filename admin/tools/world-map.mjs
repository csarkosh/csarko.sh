#!/usr/bin/env node
/**
 * Writes admin/public/world.js, the flat world the csarko.sh page marks its visitors' cities on
 * (Cyrus, 2026-11-21, as Day Hike's admin has): Natural Earth's land and borders at 1:110m (from
 * `world-atlas`), Antarctica left off, drawn once here in the Equal Earth projection with `d3-geo`
 * and kept as two SVG paths, so the page carries no map library. Beside them it writes `project`,
 * the same projection in a few lines (d3-geo's Equal Earth, rotated and fitted as here), which the
 * page uses to place a city by its coordinates; admin/test/world.test.mjs holds it to d3's.
 *
 *   node admin/tools/world-map.mjs           write it
 *   node admin/tools/world-map.mjs --check   exit 1 if it is stale
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { geoEqualEarth, geoPath } from "d3-geo";
import { feature, mesh } from "topojson-client";

export const WIDTH = 960;
export const HEIGHT = 420;
export const ROTATE = -11;

const world = JSON.parse(readFileSync(fileURLToPath(new URL("../node_modules/world-atlas/countries-110m.json", import.meta.url)), "utf8"));
// Antarctica (ISO 010) is left off: no one visits from it, and in this projection it is a wide band of nothing.
const geometries = world.objects.countries.geometries.filter((g) => String(g.id) !== "010");
const objects = { ...world.objects.countries, geometries };
const LAND = feature(world, objects);
const BORDERS = mesh(world, objects, (a, b) => a !== b);

/** The projection the map is drawn in, fitted to its box. */
export function projection() {
  return geoEqualEarth().rotate([ROTATE, 0]).fitSize([WIDTH, HEIGHT], LAND);
}

/** A path's numbers to one decimal: the map is drawn at 960 wide, so a tenth of a unit is invisible. */
const short = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));

export function source() {
  const p = projection();
  const path = geoPath(p);
  const [tx, ty] = p.translate();
  return `// Generated by admin/tools/world-map.mjs from world-atlas (Natural Earth, public domain); do not edit.
// The flat world the csarko.sh page marks its visitors' cities on: the land and borders in the
// Equal Earth projection, Antarctica left off, and \`project\`, that projection for a city's coordinates.

export const WIDTH = ${WIDTH};
export const HEIGHT = ${HEIGHT};
export const LAND = ${JSON.stringify(short(path(LAND)))};
export const BORDERS = ${JSON.stringify(short(path(BORDERS)))};

const SCALE = ${p.scale()};
const TX = ${tx};
const TY = ${ty};
const ROTATE = ${ROTATE};
const A1 = 1.340264, A2 = -0.081106, A3 = 0.000893, A4 = 0.003796, M = Math.sqrt(3) / 2;
const RAD = Math.PI / 180;

/** [x, y] on the map for a longitude and latitude in degrees (d3-geo's Equal Earth, as drawn). */
export function project(lon, lat) {
  let lambda = (lon + ROTATE) % 360;
  if (lambda > 180) lambda -= 360;
  if (lambda < -180) lambda += 360;
  lambda *= RAD;
  const l = Math.asin(M * Math.sin(lat * RAD));
  const l2 = l * l;
  const l6 = l2 * l2 * l2;
  const x = (lambda * Math.cos(l)) / (M * (A1 + 3 * A2 * l2 + l6 * (7 * A3 + 9 * A4 * l2)));
  const y = l * (A1 + A2 * l2 + l6 * (A3 + A4 * l2));
  return [TX + SCALE * x, TY - SCALE * y];
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = fileURLToPath(new URL("../public/world.js", import.meta.url));
  const next = source();
  if (process.argv.includes("--check")) {
    let now = "";
    try { now = readFileSync(out, "utf8"); } catch {}
    if (now !== next) { console.error("admin/public/world.js is stale: run node admin/tools/world-map.mjs"); process.exit(1); }
  } else {
    writeFileSync(out, next);
    console.log(`wrote ${out} (${next.length} bytes)`);
  }
}
